#!/usr/bin/env node
'use strict';

/**
 * Writes build/logo/maties-mark.svg: the Maties mark as one tapered brush
 * stroke, traced by hand from the founder's logo (September 10, 2026) as a
 * centre line with a thickness at each point. Replace the SVG with the
 * founder's own vector file when it lands; this script is only the bridge.
 */

const fs = require('fs');
const path = require('path');

// x, y, half-width, in a 1920 x 1920 frame (the founder's image).
const CENTRE_LINE = [
  [290, 1190, 132],
  [410, 1095, 136],
  [590, 935, 140],
  [770, 775, 140],
  [895, 690, 134],
  [985, 745, 118],
  [1035, 860, 100],
  [1090, 920, 98],
  [1180, 900, 112],
  [1300, 878, 124],
  [1430, 940, 120],
  [1550, 1050, 108],
  [1650, 1080, 96],
  [1710, 1045, 88],
];

const SAMPLES_PER_SEGMENT = 12;

const catmullRom = (p0, p1, p2, p3, t) => {
  const t2 = t * t;
  const t3 = t2 * t;
  return p0.map((_, index) => 0.5 * (
    2 * p1[index]
    + (-p0[index] + p2[index]) * t
    + (2 * p0[index] - 5 * p1[index] + 4 * p2[index] - p3[index]) * t2
    + (-p0[index] + 3 * p1[index] - 3 * p2[index] + p3[index]) * t3
  ));
};

const points = [];
for (let index = 0; index < CENTRE_LINE.length - 1; index += 1) {
  const p0 = CENTRE_LINE[Math.max(0, index - 1)];
  const p1 = CENTRE_LINE[index];
  const p2 = CENTRE_LINE[index + 1];
  const p3 = CENTRE_LINE[Math.min(CENTRE_LINE.length - 1, index + 2)];
  for (let step = 0; step < SAMPLES_PER_SEGMENT; step += 1) {
    points.push(catmullRom(p0, p1, p2, p3, step / SAMPLES_PER_SEGMENT));
  }
}
points.push(CENTRE_LINE[CENTRE_LINE.length - 1]);

// Every small piece is stroked with its own width and round caps; the
// pieces overlap into one smooth, tapered brush stroke.
const pieces = [];
for (let index = 0; index < points.length - 1; index += 1) {
  const [x1, y1, w1] = points[index];
  const [x2, y2, w2] = points[index + 1];
  const width = (w1 + w2);
  pieces.push(`  <path d="M ${x1.toFixed(1)} ${y1.toFixed(1)} L ${x2.toFixed(1)} ${y2.toFixed(1)}" stroke-width="${width.toFixed(1)}" />`);
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="120 500 1720 860" width="1720" height="860">
  <!-- Generated by scripts/generate-maties-mark.cjs; edit the centre line there. -->
  <g fill="none" stroke="#000000" stroke-linecap="round" stroke-linejoin="round">
${pieces.join('\n')}
  </g>
</svg>
`;

const out = path.join(__dirname, '..', 'build', 'logo', 'maties-mark.svg');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, svg);
console.log(`[brand] wrote ${path.relative(process.cwd(), out)} (${pieces.length} pieces)`);
