#!/usr/bin/env node
// `npm run vendor:playwright-core` (2 October 2026): packs the pinned
// playwright-core (package.json devDependencies) into
// source/host/runner/tools/sand-browser-playwright.gen.ts, which the host
// program carries to the cloud computer. The browser helper there drives
// Chrome with playwright-core; when the computer's image has none, the host
// writes this copy beside the helper (sand-browser-tools.ts).
//
// The copy is playwright-core's own layout cut to what the helper loads:
// package.json and browsers.json at the root (the library reads both from
// there at load) and the whole library as one file under lib/. chromium-bidi
// is left out: it is only for the WebDriver BiDi protocol, which the helper
// never uses (it attaches to Chrome over CDP). The Apache-2.0 LICENSE, NOTICE
// and ThirdPartyNotices.txt travel with it.
//
// Each file is gzip-compressed and base64-encoded, with the sha256 of its
// bytes, so the host can name the folder by content and a test can check the
// generated file still matches the installed package.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

import { build } from "esbuild";

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const PLAYWRIGHT_GEN_PATH = path.join(desktopRoot, "source/host/runner/tools/sand-browser-playwright.gen.ts");
const require = createRequire(path.join(desktopRoot, "package.json"));

export async function playwrightCoreFiles() {
  const root = path.dirname(require.resolve("playwright-core/package.json"));
  const pinned = JSON.parse(await readFile(path.join(desktopRoot, "package.json"), "utf8")).devDependencies["playwright-core"];
  const installed = JSON.parse(await readFile(path.join(root, "package.json"), "utf8")).version;
  if (installed !== pinned) throw new Error(`playwright-core ${installed} is installed but package.json pins ${pinned}; run npm ci`);
  const result = await build({
    stdin: {
      contents: 'module.exports = { core: require("playwright-core"), utilsBundle: require("playwright-core/lib/utilsBundle") };',
      resolveDir: desktopRoot,
      sourcefile: "playwright-core-entry.cjs",
      loader: "js",
    },
    bundle: true,
    platform: "node",
    target: "node18",
    format: "cjs",
    minify: true,
    legalComments: "none",
    external: ["chromium-bidi", "chromium-bidi/*"],
    write: false,
    logLevel: "error",
  });
  const files = {
    "package.json": await readFile(path.join(root, "package.json")),
    "browsers.json": await readFile(path.join(root, "browsers.json")),
    "LICENSE": await readFile(path.join(root, "LICENSE")),
    "NOTICE": await readFile(path.join(root, "NOTICE")),
    "ThirdPartyNotices.txt": await readFile(path.join(root, "ThirdPartyNotices.txt")),
    "lib/playwright-core.cjs": Buffer.from(result.outputFiles[0].contents),
  };
  return { version: installed, files };
}

export const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

export async function renderPlaywrightGen() {
  const { version, files } = await playwrightCoreFiles();
  const entries = Object.entries(files).map(([name, bytes]) => {
    const encoded = gzipSync(bytes, { level: 9 }).toString("base64");
    return `  ${JSON.stringify(name)}: {\n    sha256: ${JSON.stringify(sha256(bytes))},\n    gzipBase64:\n      ${JSON.stringify(encoded)},\n  },`;
  });
  return [
    "// Generated by scripts/vendor-playwright-core.mjs from playwright-core",
    `// ${version} (Apache-2.0, Microsoft Corporation; its LICENSE and NOTICE are`,
    "// among the files). Do not edit; run `npm run vendor:playwright-core`.",
    `export const SAND_BROWSER_PLAYWRIGHT_VERSION = ${JSON.stringify(version)};`,
    "",
    "export const SAND_BROWSER_PLAYWRIGHT_FILES: Readonly<Record<string, { readonly sha256: string; readonly gzipBase64: string }>> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await renderPlaywrightGen();
  await writeFile(PLAYWRIGHT_GEN_PATH, text);
  console.log(`wrote ${path.relative(desktopRoot, PLAYWRIGHT_GEN_PATH)} (${(text.length / 1024 / 1024).toFixed(2)} MB)`);
}
