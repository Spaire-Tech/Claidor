/**
 * The connectors' logos, embedded (6 October 2026).
 *
 * Until today the connectors panel drew four Google products (Gmail,
 * Calendar, Drive, Meet) with the same picture, the Google "G", and
 * fetched 45 others live from Google's favicon service, which answers a
 * generic icon for a product domain such as slides.google.com. The
 * founder saw Slides and Calendar without their marks and asked why.
 *
 * Now every connector in `source/shared/node/vendor-mcp/catalog.ts` has
 * its product mark as a file under `brand/connector-logos/<id>.svg` (or
 * `.png` for the one whose vector was a 174 KB trace, Cal.com), and this
 * script writes them into `source/shared/node/vendor-mcp/logo-data.ts`
 * as data URLs, so the app needs no network for a logo and no third
 * party sees who opened the panel. The marks are each vendor's own; 65
 * came from Composio's logo service (logos.composio.dev/api/<toolkit>),
 * Mercury's from mercury.com/favicon.svg, since Composio has none.
 *
 *   node scripts/make-connector-logos.mjs
 *
 * Run it after adding a connector to the catalog and its file to the
 * folder; the test `tests/connector-logos.test.mjs` fails on a connector
 * with no logo, a logo that is the Google G or a placeholder, or a
 * generated file older than its sources.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const LOGO_DIR = path.join(desktopRoot, "brand", "connector-logos");
export const OUT_FILE = path.join(desktopRoot, "source", "shared", "node", "vendor-mcp", "logo-data.ts");

const MEDIA = { ".svg": "image/svg+xml", ".png": "image/png", ".webp": "image/webp" };

/** `<id>.svg` and friends in the folder, as `{ id, dataUrl }`, sorted by id. */
export async function readConnectorLogos(dir = LOGO_DIR) {
  const entries = [];
  for (const file of (await readdir(dir)).sort()) {
    const ext = path.extname(file);
    const type = MEDIA[ext];
    if (type == null) continue;
    const bytes = await readFile(path.join(dir, file));
    const body = ext === ".svg" ? Buffer.from(bytes.toString("utf8").replace(/\s*\n\s*/g, " ").trim()) : bytes;
    entries.push({ id: file.slice(0, -ext.length), dataUrl: `data:${type};base64,${body.toString("base64")}` });
  }
  return entries;
}

export function renderLogoData(entries) {
  const lines = entries.map(({ id, dataUrl }) => `  ${JSON.stringify(id)}: ${JSON.stringify(dataUrl)},`);
  return [
    "// Generated by scripts/make-connector-logos.mjs from brand/connector-logos/. Do not edit.",
    "// Each connector's own product mark, embedded so the panel needs no network for a logo.",
    "export const CONNECTOR_LOGOS: Readonly<Record<string, string>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

const invokedDirectly = process.argv[1] != null && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const entries = await readConnectorLogos();
  await writeFile(OUT_FILE, renderLogoData(entries));
  console.log(`${entries.length} logos written to ${path.relative(desktopRoot, OUT_FILE)}`);
}
