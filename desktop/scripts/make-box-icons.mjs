/**
 * The cloud computer's folder icon, for the host to put in the dock (26
 * October 2026, the founder: "something like a mac folder"), after the
 * wallpaper's own (`make-box-wallpaper.mjs`).
 *
 * The computers in service run the earlier maker's image, whose dock (Plank)
 * shows the file manager (Thunar) under its own icon, `org.xfce.thunar`.
 * The host writes ours under that name in the dock's own icon folder
 * (`host/extensions/wallpaper/box-folder-icon.ts`), which comes before the
 * system's. This script embeds `box/icons/files.svg` and its pictures at
 * each size, `box/icons/files-<size>.png` (drawn from the SVG by a browser),
 * as hex: no earlier name can be spelt in it, which base64 could.
 *
 *   node scripts/make-box-icons.mjs
 *
 * The test `tests/box-wallpaper.test.mjs` fails when the embedded copy and
 * the files differ.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const ICONS_DIR = path.resolve(desktopRoot, "..", "box", "icons");
export const ICON_SIZES = [16, 22, 24, 32, 48, 64, 96, 128, 256, 512];
export const OUT_FILE = path.join(desktopRoot, "source", "host", "extensions", "wallpaper", "folder-icon.generated.ts");

export function renderIconsModule(svg, pictures) {
  return [
    "// Generated by scripts/make-box-icons.mjs from box/icons/. Do not edit.",
    "// The dock's folder icon: the SVG, then a PNG at each size, as hex.",
    `export const FOLDER_ICON_SVG_HEX = ${JSON.stringify(Buffer.from(svg).toString("hex"))};`,
    "export const FOLDER_ICON_PNG_HEX: Readonly<Record<number, string>> = {",
    ...ICON_SIZES.map((size) => `  ${size}: ${JSON.stringify(Buffer.from(pictures[size]).toString("hex"))},`),
    "};",
    "",
  ].join("\n");
}

export async function readIcons() {
  const svg = await readFile(path.join(ICONS_DIR, "files.svg"));
  const pictures = {};
  for (const size of ICON_SIZES) pictures[size] = await readFile(path.join(ICONS_DIR, `files-${size}.png`));
  return { svg, pictures };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { svg, pictures } = await readIcons();
  await writeFile(OUT_FILE, renderIconsModule(svg, pictures));
  console.log(`folder icon, ${ICON_SIZES.length} sizes -> ${path.relative(desktopRoot, OUT_FILE)}`);
}
