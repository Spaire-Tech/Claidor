/**
 * The cloud computer's wallpaper, for the host to paint (9 October 2026,
 * the founder: the photograph of a river under a storm at sunset, the one
 * the onboarding's computer step already shows, as the computer's own).
 *
 * The computers in service run the earlier maker's image, whose wallpaper is
 * baked into it; Simeon's own image (`box/`) carries the photograph in
 * `box/wallpapers/`. So that every computer shows it now, the host writes
 * the same picture to a folder of its own and points the image's
 * `sand-wallpaper` at it (`host/extensions/wallpaper`). This script embeds
 * `box/wallpapers/simeon-b.png` in the host as hex (hex: no earlier name can
 * be spelt in it, which base64 could).
 *
 *   node scripts/make-box-wallpaper.mjs
 *
 * The test `tests/box-wallpaper.test.mjs` fails when the embedded copy and
 * the file differ.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const WALLPAPER_FILE = path.resolve(desktopRoot, "..", "box", "wallpapers", "simeon-b.png");
export const OUT_FILE = path.join(desktopRoot, "source", "host", "extensions", "wallpaper", "simeon-wallpaper.generated.ts");

export function renderWallpaperModule(bytes) {
  return [
    "// Generated by scripts/make-box-wallpaper.mjs from box/wallpapers/simeon-b.png. Do not edit.",
    "// The cloud computer's wallpaper (a 1280 by 800 JPEG), as hex.",
    `export const SIMEON_WALLPAPER_HEX = ${JSON.stringify(Buffer.from(bytes).toString("hex"))};`,
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const bytes = await readFile(WALLPAPER_FILE);
  await writeFile(OUT_FILE, renderWallpaperModule(bytes));
  console.log(`wallpaper ${bytes.length} bytes -> ${path.relative(desktopRoot, OUT_FILE)}`);
}
