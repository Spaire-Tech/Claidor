#!/usr/bin/env node
/**
 * The Mac's lists of women's and men's first names, for the iPhone app.
 *
 *   node ios/scripts/make-name-genders.mjs
 *
 * Writes ios/SimeonCore/Sources/SimeonCore/GeneratedNameGenders.swift from
 * desktop/source/shared/voice-call/name-genders.ts, so the phone gives an
 * agent a woman's or a man's voice by its name exactly as the Mac does
 * (AgentVoices.swift; the Mac's agent-voices.ts). A core test fails when the
 * two differ.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const source = path.join(root, "desktop/source/shared/voice-call/name-genders.ts");
const out = path.join(root, "ios/SimeonCore/Sources/SimeonCore/GeneratedNameGenders.swift");

/** The words of `export const <name> = "…" + "…" …;`. */
export function namesIn(text, name) {
  const start = text.indexOf(`export const ${name} =`);
  if (start < 0) throw new Error(`${name} is not in ${source}`);
  const end = text.indexOf(";", start);
  const literals = [...text.slice(start, end).matchAll(/"([^"]*)"/g)].map((match) => match[1]);
  return literals.join("").split(" ").filter((word) => word.length > 0);
}

export function renderNameGenders(text) {
  // One multi-line literal each: a long chain of `+` is slow for Swift's type checker.
  const block = (words) => {
    const rows = [];
    for (let index = 0; index < words.length; index += 16) rows.push(`    ${words.slice(index, index + 16).join(" ")}`);
    return ['    """', ...rows, '    """'].join("\n");
  };
  return [
    "// Generated by ios/scripts/make-name-genders.mjs from",
    "// desktop/source/shared/voice-call/name-genders.ts. Do not edit by hand.",
    "",
    "/** First names given to at least 85% girls or boys, most common first: the Mac's `WOMEN_NAMES` and `MEN_NAMES`, one or more spaces or lines between names. */",
    "enum GeneratedNameGenders {",
    "  static let women =",
    block(namesIn(text, "WOMEN_NAMES")),
    "  static let men =",
    block(namesIn(text, "MEN_NAMES")),
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await readFile(source, "utf8");
  await writeFile(out, renderNameGenders(text));
  console.log(`wrote ${path.relative(root, out)}: ${namesIn(text, "WOMEN_NAMES").length} women's names, ${namesIn(text, "MEN_NAMES").length} men's`);
}
