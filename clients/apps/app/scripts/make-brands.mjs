// The apps a message can name, with their colours and logos, for the web
// app: read from the table the iPhone and the Mac use
// (ios/SimeonCore/Sources/SimeonCore/GeneratedBrands.swift, made by
// ios/scripts/make-assets.mjs), each logo taken from the file the Mac's own
// logo is drawn from (desktop/brand: app-logos/apps.json, then
// ios/scripts/connector-mentions.json). So a connector added for the Mac
// (CLAUDE.md, "A new connector is named in the chat in its colour") is here
// when this is run again.
//
//   node scripts/make-brands.mjs          writes src/core/generatedBrands.ts
//   node scripts/make-brands.mjs --check  fails when it is out of date
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../../../../', import.meta.url))
const out = fileURLToPath(
  new URL('../src/core/generatedBrands.ts', import.meta.url),
)
const swift = readFileSync(
  `${root}ios/SimeonCore/Sources/SimeonCore/GeneratedBrands.swift`,
  'utf8',
)
const apps = JSON.parse(
  readFileSync(`${root}desktop/brand/app-logos/apps.json`, 'utf8'),
)
const extra = JSON.parse(
  readFileSync(`${root}ios/scripts/connector-mentions.json`, 'utf8'),
)

// Each logo's file, from src/core (where the table is read), as the Mac's script draws it.
const logo = new Map()
for (const app of apps)
  logo.set(app.key, `../../../../../desktop/brand/app-logos/${app.logo}`)
for (const app of extra.apps)
  logo.set(app.key, `../../../../../desktop/brand/${app.logo}`)

const row =
  /BrandMention\(name: ("(?:[^"\\]|\\.)*"), key: ("(?:[^"\\]|\\.)*"), light: ("[^"]*"), dark: ("[^"]*"), mono: (true|false), ordinaryWord: (true|false)\)/g
const rows = [...swift.matchAll(row)].map((m) => ({
  name: JSON.parse(m[1]),
  key: JSON.parse(m[2]),
  light: JSON.parse(m[3]),
  dark: JSON.parse(m[4]),
  mono: m[5] === 'true',
  ordinaryWord: m[6] === 'true',
}))
if (rows.length === 0)
  throw new Error('No BrandMention rows in GeneratedBrands.swift')
const keys = [...new Set(rows.map((r) => r.key))].sort()
const missing = keys.filter((key) => !logo.has(key))
if (missing.length > 0) throw new Error(`No logo for ${missing.join(', ')}`)

const text = `// Generated by scripts/make-brands.mjs from GeneratedBrands.swift and the
// Mac's logo sources (desktop/brand). Do not edit by hand: run \`pnpm brands\`.

/** An app a message can name (\`BrandMention\`): the spelling, its logo's key, its colour in light and dark, whether its logo is one colour (tinted like the name), and whether the name is also an everyday word. */
export interface BrandMention {
  name: string
  key: string
  light: string
  dark: string
  mono: boolean
  ordinaryWord: boolean
}

/** Every spelling, longest first, as the Mac matches them (\`Brands.mentions\`). */
export const brandMentions: BrandMention[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
]

/** Each app's logo, the file the Mac's is drawn from. */
export const brandLogos: Record<string, string> = {
${keys.map((key) => `  ${JSON.stringify(key)}: new URL(${JSON.stringify(logo.get(key))}, import.meta.url).href,`).join('\n')}
}
`

if (process.argv.includes('--check')) {
  let kept = ''
  try {
    kept = readFileSync(out, 'utf8')
  } catch {
    // Not made yet.
  }
  if (kept !== text) {
    console.error(
      'src/core/generatedBrands.ts is out of date: run `pnpm brands` in clients/apps/app and commit it.',
    )
    process.exit(1)
  }
  console.log(
    `The brands are the core's (${rows.length} spellings, ${keys.length} logos).`,
  )
} else {
  writeFileSync(out, text)
  console.log(`Wrote ${rows.length} spellings and ${keys.length} logos.`)
}
