// The connectors' written pages for the web app (who makes each, a few
// lines on it, three messages naming it, its maker's three links): read
// from the shared core's own (ios/SimeonCore/Sources/SimeonCore/
// ConnectorPages.swift, `ConnectorPage.page(for:)` and `written`), so a page
// written for the Mac and the iPhone is here when this is run again. Each
// sentence is written as its own `t(…)` call, made only when its page is
// asked for, so the words' checks (`check_translations.py`, the inventory)
// find every one in the core's catalogue.
//
//   node scripts/make-connector-pages.mjs          writes src/core/writtenConnectorPages.ts
//   node scripts/make-connector-pages.mjs --check  fails when it is out of date (run by `pnpm test`)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../../../../', import.meta.url))
const out = fileURLToPath(
  new URL('../src/core/writtenConnectorPages.ts', import.meta.url),
)
const swift = readFileSync(
  `${root}ios/SimeonCore/Sources/SimeonCore/ConnectorPages.swift`,
  'utf8',
)

/** A Swift string literal's text; one with a value in it (`\(…)`) is not a written page's, and stops the script. */
function swiftString(literal) {
  if (literal.includes('\\(')) throw new Error(`A value in ${literal}`)
  const json = literal.replace(/\\u\{([0-9a-fA-F]+)\}/g, (_, hex) =>
    String.fromCodePoint(parseInt(hex, 16)),
  )
  return JSON.parse(json)
}

const string = '("(?:[^"\\\\]|\\\\.)*")'
const words = `L10n\\.text\\(${string}\\)`
const page = new RegExp(
  `case ${string}:\\s*return page\\(${string}, site: ${string}, privacy: ${string}, terms: ${string},\\s*about: ${words},\\s*${words},\\s*${words},\\s*${words}\\)`,
  'g',
)
const pages = [...swift.matchAll(page)].map((m) => ({
  id: swiftString(m[1]),
  maker: swiftString(m[2]),
  site: swiftString(m[3]),
  privacy: swiftString(m[4]),
  terms: swiftString(m[5]),
  about: swiftString(m[6]),
  examples: [m[7], m[8], m[9]].map(swiftString),
}))
// Every case is a page of this shape: one written another way would be missed.
const cases = [...swift.matchAll(/^ {4}case "/gm)].length
if (pages.length === 0 || pages.length !== cases)
  throw new Error(
    `Read ${pages.length} pages of ${cases} cases in ConnectorPages.swift`,
  )
const list = swift.match(/public static let written = \[([^\]]*)\]/)
if (!list) throw new Error('No `written` list in ConnectorPages.swift')
const written = [...list[1].matchAll(new RegExp(string, 'g'))].map((m) =>
  swiftString(m[1]),
)

// Written as the app's code is written (single quotes), so the table is Prettier's own.
const q = (value) => {
  if (/[\n\r\u2028\u2029]/.test(value))
    throw new Error(`A line break in ${value}`)
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

/** A sentence's line in a page (8 in): `t('…'),` on one line while it fits Prettier's 80, else its words on a line of their own. */
const sentence = (value) => {
  const line = `        t(${q(value)}),`
  if ([...line].length <= 80) return line
  return `        t(\n          ${q(value)},\n        ),`
}
const text = `// Generated by scripts/make-connector-pages.mjs from the core's
// ConnectorPages.swift. Do not edit by hand: run \`pnpm pages\`.

import type { ConnectorPage } from './connectorPages'
import { t } from './l10n'

/** A page from its maker, its three links and its words (\`ConnectorPage.page(_:site:privacy:terms:about:_:)\`). */
function page(
  maker: string,
  website: string,
  privacy: string,
  terms: string,
  about: string,
  ...examples: string[]
): ConnectorPage {
  return { maker, about, examples, website, privacy, terms }
}

/** The written page of a catalog entry (its id, as \`gmail\`), in the app's language; none for another. */
export function writtenPage(id: string): ConnectorPage | undefined {
  switch (id) {
${pages
  .map(
    (p) => `    case ${q(p.id)}:
      return page(
        ${q(p.maker)},
        ${q(p.site)},
        ${q(p.privacy)},
        ${q(p.terms)},
${[p.about, ...p.examples].map(sentence).join('\n')}
      )`,
  )
  .join('\n')}
    default:
      return undefined
  }
}

/** The connectors written so far (\`ConnectorPage.written\`), for the tests. */
export const written: readonly string[] = [
${written.map((id) => `  ${q(id)},`).join('\n')}
]
`

if (process.argv.includes('--check')) {
  let kept = ''
  try {
    kept = readFileSync(out, 'utf8')
  } catch {
    // Not made yet.
  }
  if (kept !== text) {
    console.error(
      'src/core/writtenConnectorPages.ts is out of date: run `pnpm pages` in clients/apps/app and commit it.',
    )
    process.exit(1)
  }
  console.log(
    `The connector pages are the core's (${pages.length} pages, ${written.length} written).`,
  )
} else {
  writeFileSync(out, text)
  console.log(`Wrote ${pages.length} pages (${written.length} written).`)
}
